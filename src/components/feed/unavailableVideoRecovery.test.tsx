import React from 'react';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
const mock = vi.hoisted(() => ({ write: vi.fn(), toast: vi.fn(), success: vi.fn(), payload: null as any }));
vi.mock('@/contexts/AuthContext', () => ({ useAuth: () => ({ user: { id: 'owner', user_metadata: {} } }) }));
vi.mock('@/hooks/useAuthPrompt', () => ({ useAuthPrompt: () => ({ requireAuth: () => true }) }));
vi.mock('@/hooks/use-toast', () => ({ useToast: () => ({ toast: mock.toast }) }));
vi.mock('@/hooks/useMuxStatus', () => ({ useMuxStatus: () => ({ A: { ui_status: 'ready', asset_id: 'asset-A', playback_id: 'play-A', duration: 5 }, B: { ui_status: 'ready', asset_id: 'asset-B', playback_id: 'play-B', duration: 5 } }) }));
vi.mock('@/services/analytics', () => ({ analytics: { track: vi.fn() } }));
vi.mock('@/services/feedbackService', () => ({ triggerHaptic: vi.fn(), playSound: vi.fn() }));
vi.mock('@/services/muxAbandonment', () => ({ abandonMuxUploads: vi.fn(), flushMuxAbandonments: vi.fn(), sessionNewMuxIds: () => [] }));
vi.mock('@/integrations/supabase/client', () => ({ supabase: { from: () => {
  const chain: any = { insert: (p: any) => { mock.payload = p; return chain; }, update: (p: any) => { mock.payload = p; return chain; }, eq: () => chain, select: () => chain, single: () => mock.write() }; return chain;
} } }));
vi.mock('@/components/feed/composer/ComposerBottomBar', () => ({ ComposerBottomBar: () => null }));
vi.mock('@/components/feed/UnifiedEntitySelector', () => ({ UnifiedEntitySelector: () => null }));
vi.mock('@/components/feed/composer/EntityHeroPill', () => ({ EntityHeroPill: () => null }));
vi.mock('@/components/feed/composer/EntitySelectorModal', () => ({ EntitySelectorModal: () => null }));
vi.mock('@/components/feed/composer/PostTypeAndTagsModal', () => ({ PostTypeAndTagsModal: () => null }));
vi.mock('@/components/feed/composer/PostTypeAndTagsPill', () => ({ PostTypeAndTagsPill: () => null }));
vi.mock('@/components/feed/composer/MoreToolsPopover', () => ({ MoreToolsPopover: () => null }));
vi.mock('@/components/feed/composer/DiscardDraftDialog', () => ({ DiscardDraftDialog: () => null }));
vi.mock('@/components/feed/LocationSearchInput', () => ({ LocationSearchInput: () => null }));
vi.mock('@emoji-mart/react', () => ({ default: () => null }));
vi.mock('@/components/feed/composer/ComposerMediaPreview', () => ({ ComposerMediaPreview: (p: any) => <>{p.media.map((m: any) => <React.Fragment key={m.id}>{p.recoveryForItem?.(m) || <button onClick={() => p.onRemove(m)}>Remove {m.type}</button>}</React.Fragment>)}</> }));
const video = { id: 'a', clientKey: 'local-a', type: 'video', provider: 'mux', mux_upload_id: 'A', url: 'poster', order: 0 };
vi.mock('@/components/media/MediaUploader', () => ({ UploadRow: () => null, MediaUploader: (p: any) => p.customButton && p.videoReplacementOnly ? <button disabled={p.disabled} onClick={() => p.onMediaUploaded({ ...video, id: 'b', clientKey: 'local-b', mux_upload_id: 'B' })}>Replace</button> : <><button onClick={() => p.onMediaUploaded(video)}>Attach A</button><button onClick={() => p.onMediaUploaded({ id: 'photo', type: 'image', url: 'kept-photo', order: 1 })}>Attach photo</button></> }));
import { EnhancedCreatePostForm } from './EnhancedCreatePostForm';
beforeEach(() => { localStorage.clear(); mock.write.mockReset(); mock.toast.mockClear(); mock.success.mockClear(); mock.write.mockResolvedValue({ error: { code: 'P0001', message: 'video_unavailable' }, data: null }); });
afterEach(cleanup);
describe('real Post submit-handler recovery', () => {
  for (const edit of [false, true]) it(`${edit ? 'edit' : 'create'} keeps draft and blocks the rejected upload`, async () => {
    render(<QueryClientProvider client={new QueryClient()}><EnhancedCreatePostForm onSuccess={mock.success} postToEdit={edit ? { id: 'p1', content: 'initial draft', title: 'kept title', media: [] } : undefined} /></QueryClientProvider>);
    const text = screen.getAllByRole('textbox')[1];
    fireEvent.change(text, { target: { value: 'preserve all written work' } });
    fireEvent.click(screen.getByText('Attach A')); fireEvent.click(screen.getByText('Attach photo'));
    const submits = () => screen.getAllByRole('button', { name: edit ? /^Update$/ : /^Post$/ });
    fireEvent.click(submits()[0]);
    await waitFor(() => expect(mock.toast).toHaveBeenCalledWith(expect.objectContaining({ title: 'Video no longer available', variant: 'destructive' })));
    expect(mock.success).not.toHaveBeenCalled(); expect(text).toHaveValue('preserve all written work');
    expect(screen.getByText('Remove image')).toBeInTheDocument();
    fireEvent.change(text, { target: { value: 'still blocked after text edit' } });
    submits().forEach((button) => expect(button).toBeDisabled());
    fireEvent.click(submits()[0]); expect(mock.write).toHaveBeenCalledOnce();
    fireEvent.click(screen.getByText('Replace'));
    expect(screen.queryByText('Video no longer available')).toBeNull();
    expect(text).toHaveValue('still blocked after text edit');
    submits().forEach((button) => expect(button).toBeEnabled());
    mock.write.mockResolvedValue({ data: null, error: { code: 'P0001', message: 'unrelated_save_failure' } });
    fireEvent.click(submits()[0]);
    await waitFor(() => expect(mock.write).toHaveBeenCalledTimes(2));
    await waitFor(() => submits().forEach((button) => expect(button).toBeEnabled()));
    expect(mock.payload.media.map((m: any) => m.mux_upload_id || m.url)).toEqual(['kept-photo', 'B']);
    expect(mock.success).not.toHaveBeenCalled();
    expect(text).toHaveValue('still blocked after text edit');
    expect(screen.queryByText('Video no longer available')).toBeNull();
    fireEvent.click(screen.getByText('Remove video'));
    submits().forEach((button) => expect(button).toBeEnabled());
  });
});